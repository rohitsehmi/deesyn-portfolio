/**
 * Fetches the Figma, GitHub and Storybook brand marks and writes them to
 * src/components/service-marks.ts.
 *
 *   node design/build-service-marks.mjs
 *
 * Generated rather than drawn, for the same reason the favicon is: a
 * hand-traced logo is a wrong logo, and someone else's mark is the one place
 * "close enough" is actually a problem.
 *
 * Source is Simple Icons, whose path data is CC0. The marks themselves are the
 * trademarks of their owners and are used here only to label a link to that
 * service, which is what they are for. Not modified beyond being extracted.
 *
 * Deliberately NOT part of the Icon component and NOT in icons/specs:
 *
 * - `Icon` is contracted as real Revolut assets taken verbatim from
 *   assets.revolut.com, it has a Figma component set behind it, and it is
 *   checksummed. Putting three third-party logos in it would make all three of
 *   those statements false.
 * - A `.ts` and not a `.tsx` on purpose. Component counts on
 *   /how-this-was-built are computed by counting .tsx files, and
 *   build-code-specs.mjs generates a contract for each one. A brand mark is an
 *   asset, not a component, and should move neither number.
 *
 * Not part of `npm run specs`: it needs the network, and these three marks
 * change roughly never. Re-run it by hand if one is restyled.
 */
import { writeFileSync } from 'node:fs';

const SERVICES = [
  ['figma', 'Figma'],
  ['github', 'GitHub'],
  ['storybook', 'Storybook']
];

const marks = [];

for (const [slug, name] of SERVICES) {
  const res = await fetch(`https://cdn.simpleicons.org/${slug}`);
  if (!res.ok) throw new Error(`${slug}: ${res.status}`);
  const svg = await res.text();

  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1];
  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]);
  if (!viewBox || !paths.length) throw new Error(`${slug}: could not parse`);

  marks.push({ slug, name, viewBox, paths });
  console.log(`${name.padEnd(10)} ${paths.length} path(s), viewBox ${viewBox}`);
}

const file = `/**
 * Brand marks for the services linked from /how-this-was-built.
 *
 * GENERATED by design/build-service-marks.mjs — do not edit by hand.
 * Path data from Simple Icons (CC0). The marks are the trademarks of their
 * owners, used here only to label a link to that service.
 *
 * These are assets, not components, and deliberately live outside the Icon
 * component and its published contract: Icon is real Revolut assets with a
 * Figma set and a checksum behind it. See the generator for the full reasoning.
 *
 * Rendered with fill: currentColor rather than in brand colours. Three saturated
 * logos would fight each other and the page, GitHub's near-black would disappear
 * against a dark band, and the marks sit inside links that already carry a
 * colour. Monochrome is the honest choice here, not a shortcut.
 */
export interface ServiceMark {
  name: string;
  viewBox: string;
  paths: string[];
}

export const SERVICE_MARKS: Record<string, ServiceMark> = ${JSON.stringify(
  Object.fromEntries(marks.map((m) => [m.slug, { name: m.name, viewBox: m.viewBox, paths: m.paths }])),
  null,
  2
)};
`;

writeFileSync('src/components/service-marks.ts', file);
console.log('\nwrote src/components/service-marks.ts');