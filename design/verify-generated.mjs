#!/usr/bin/env node
/**
 * Regenerating must change nothing.
 *
 * Tokens, specs, the favicon and the OG card are all derived — from Figma, from
 * component source, from the brand mark. If running the generators produces a
 * diff, then an output was hand-edited instead of its source being changed and
 * re-exported, and the file now disagrees with the thing it claims to be
 * measured from. That is invisible in review, because the change you would be
 * looking for is the one that never got made.
 *
 * This ran only in CI until 2026-08-18, which meant the machine that could have
 * told you in two seconds stayed quiet and the one that told you after a push
 * went red. The pre-commit hook already regenerates and stages when a component
 * changes; this is the wider net — it also catches a hand-edited tokens.css, a
 * stale favicon, and anything regenerated by a script the hook does not watch.
 *
 *   node design/verify-generated.mjs
 *
 * Leaves any regeneration in the working tree on purpose. If it fails, the fix
 * is already sitting there staged-ready rather than something you must re-run.
 */
import { execFileSync } from 'node:child_process';
import { GENERATED } from './paths.mjs';

const root = new URL('../', import.meta.url).pathname;
const run = (cmd, args) =>
  execFileSync(cmd, args, { cwd: root, stdio: ['ignore', 'pipe', 'pipe'] }).toString();

try {
  run('npm', ['run', 'tokens']);
  run('npm', ['run', 'specs']);
} catch (e) {
  console.error('\ngenerated files: a generator failed, so staleness cannot be judged\n');
  console.error(e.stderr?.toString() || e.message);
  process.exit(1);
}

/* --name-only rather than --exit-code: the point is to name what drifted, and a
   bare non-zero exit sends someone back to run the diff by hand anyway. */
const changed = run('git', ['diff', '--name-only', '--', ...GENERATED])
  .split('\n')
  .filter(Boolean);

/*
  UNTRACKED GENERATED FILES ARE THE BLIND SPOT, and this check had it on the day
  it was written. `git diff` compares the working tree against the index, so a
  generated file that has never been committed produces no diff no matter what
  is in it — the check reports "up to date" about a file it cannot see. Caught
  by hand-editing design/layout-export.json on 2026-08-18 and watching this pass.

  It is not the same failure as staleness and does not get the same message: the
  file is not wrong, it is simply not committed yet, and the fix is `git add`
  rather than reading a diff.
*/
const untracked = run('git', ['ls-files', '--others', '--exclude-standard', '--', ...GENERATED])
  .split('\n')
  .filter(Boolean);

if (changed.length || untracked.length) {
  if (changed.length) {
    console.error(`\ngenerated files — ${changed.length} stale, regenerated into your working tree:`);
    changed.forEach((f) => console.error(`  ${f}`));
    console.error('\nSomeone edited an output instead of its source. Review the diff: if it is');
    console.error('correct, commit it. If it is a surprise, the source is what needs changing.');
  }
  if (untracked.length) {
    console.error(`\ngenerated files — ${untracked.length} generated but never committed:`);
    untracked.forEach((f) => console.error(`  ${f}`));
    console.error('\nUntil these are tracked, nothing can tell whether they are stale — git diff');
    console.error('sees no change in a file it has no baseline for. Commit them.');
  }
  console.error('');
  process.exit(1);
}

console.log('\ngenerated files: up to date (regenerating is a no-op)\n');