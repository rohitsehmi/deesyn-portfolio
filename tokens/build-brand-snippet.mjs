#!/usr/bin/env node
/**
 * Generates the Figma snippet that writes a brand pack into a brand's file.
 *
 *   node tokens/build-brand-snippet.mjs     (part of: npm run specs)
 *
 * The snippet has to carry every value it writes, because a Figma plugin
 * sandbox cannot read this repo. That makes it a second copy of the pack —
 * exactly the hand-maintained duplication this codebase keeps paying for — so
 * it is GENERATED from tokens/brands/ and covered by the staleness check.
 * Change the pack, run the build, and the snippet follows. Hand-edit the
 * snippet and the build fails.
 *
 * WHY THE MAPPING LIVES HERE. The repo names a token `portfolio.teal.600` and
 * Figma names it `Portfolio/Teal/600`; the repo says `alpha.black-4` and Figma
 * says `Alpha/Black 4`. Both sides are matched on a normalised key rather than
 * by guessing one from the other, and a target that does not resolve throws at
 * build time rather than writing a half-applied palette into someone's file.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadPacks, flatten } from './brands.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const base = JSON.parse(readFileSync(join(here, 'tokens.json'), 'utf8'));

const norm = (s) => s.toLowerCase().replace(/[\s-]/g, '').replace(/\//g, '.');
const title = (s) => s.charAt(0).toUpperCase() + s.slice(1);

/**
 * The base collection's Figma names, derived from tokens.json rather than
 * typed, so a primitive renamed there is renamed here too.
 *
 * `alpha.black-4` -> `Alpha/Black 4`: the group is title-cased and the leaf's
 * hyphen becomes a space, which is the convention the Revolut file already
 * uses and which every brand file inherits by being a copy of it.
 */
function baseFigmaNames() {
  const out = [];
  for (const [path] of flatten(base.primitive)) {
    const [group, ...rest] = path.split('.');
    out.push(`${title(group)}/${rest.join('/').replace(/-/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase())}`);
  }
  return out;
}

/** `portfolio.teal.600` -> `Portfolio/Teal/600`. */
const packFigmaName = (n) => n.split('.').map((s, i) => (i < 2 ? title(s) : s)).join('/');

const packs = loadPacks();
if (packs.length !== 1) {
  throw new Error(`expected exactly one brand pack, found ${packs.length} — the snippet writes one palette`);
}
const { file, brands, pack } = packs[0];

const primitives = flatten(pack.primitive).map(([n, node]) => [packFigmaName(n), node.$value]);

const lookup = new Map(baseFigmaNames().map((n) => [norm(n), n]));
for (const [n] of primitives) lookup.set(norm(n), n);

const semantic = {};
for (const mode of ['light', 'dark']) {
  semantic[mode] = flatten(pack.semantic[mode]).map(([n, node]) => {
    const target = node.$value.slice(1, -1).replace(/^primitive\./, '');
    const fig = lookup.get(norm(target));
    if (!fig) throw new Error(`${file}: semantic.${mode}.${n} aliases {${node.$value}}, which maps to no Figma variable`);
    return [n.replace(/\./g, '/'), fig];
  });
}

const rows = (list) => list.map(([a, b]) => `${a} ${b}`).join(',');

const out = `/**
 * GENERATED by tokens/build-brand-snippet.mjs from tokens/brands/${file}.
 * Do not edit. Change the pack and rebuild.
 *
 * Writes the ${brands.join(' / ')} palette into the open Figma file: adds this
 * pack's primitives to "01 Primitives" and repoints "02 Semantic" in both
 * modes to alias them. Paste into the Figma Desktop Bridge plugin console with
 * the brand's file open, then run tokens/brand-export.snippet.js and check the
 * checksum against \`node tokens/verify-brands.mjs\`.
 *
 * It ADDS and REPOINTS; it deletes nothing. Existing primitives are left in
 * place, which is what keeps the file a superset of where it started and makes
 * running this twice harmless.
 */
const PRIM = ${JSON.stringify(rows(primitives))};
const LIGHT = ${JSON.stringify(rows(semantic.light))};
const DARK = ${JSON.stringify(rows(semantic.dark))};

const pairs = (s) => s.split(',').map((r) => { const i = r.indexOf(' '); return [r.slice(0, i), r.slice(i + 1)]; });
const hexToRgb = (h) => {
  const n = h.replace('#', '');
  const v = (i) => parseInt(n.slice(i, i + 2), 16) / 255;
  return n.length >= 8 ? { r: v(0), g: v(2), b: v(4), a: v(6) } : { r: v(0), g: v(2), b: v(4), a: 1 };
};

const cols = await figma.variables.getLocalVariableCollectionsAsync();
const prim = cols.find((c) => c.name === '01 Primitives');
const sem = cols.find((c) => c.name === '02 Semantic');
if (!prim || !sem) throw new Error('expected collections "01 Primitives" and "02 Semantic"');

const primMode = prim.modes[0].modeId;
const light = sem.modes.find((m) => m.name === 'Light');
const dark = sem.modes.find((m) => m.name === 'Dark');
if (!light || !dark) throw new Error('expected Light and Dark modes on "02 Semantic"');

const primVars = await Promise.all(prim.variableIds.map((id) => figma.variables.getVariableByIdAsync(id)));
const semVars = await Promise.all(sem.variableIds.map((id) => figma.variables.getVariableByIdAsync(id)));
const byPrim = {}; primVars.forEach((v) => { byPrim[v.name] = v; });
const bySem = {}; semVars.forEach((v) => { bySem[v.name] = v; });

let created = 0, updated = 0;
for (const [name, hex] of pairs(PRIM)) {
  let v = byPrim[name];
  if (!v) { v = figma.variables.createVariable(name, prim, 'COLOR'); byPrim[name] = v; created++; }
  else updated++;
  v.setValueForMode(primMode, hexToRgb(hex));
}

/* Collected rather than thrown on, so a rename shows every casualty at once
   instead of one per run. A partial write is still visible in the counts. */
let repointed = 0; const missing = [];
for (const [mode, list] of [[light.modeId, LIGHT], [dark.modeId, DARK]]) {
  for (const [token, target] of pairs(list)) {
    const t = bySem[token]; const src = byPrim[target];
    if (!t) { missing.push('semantic ' + token); continue; }
    if (!src) { missing.push('primitive ' + target); continue; }
    t.setValueForMode(mode, figma.variables.createVariableAlias(src));
    repointed++;
  }
}

console.log('file      :', figma.root.name);
console.log('created   :', created, 'primitives');
console.log('updated   :', updated, 'primitives');
console.log('repointed :', repointed, 'semantic bindings across both modes');
if (missing.length) console.log('MISSING   :', missing.join(', '));
return { file: figma.root.name, created, updated, repointed, missing };
`;

writeFileSync(join(here, 'brand-apply.snippet.js'), out);
console.log(`tokens/brand-apply.snippet.js written from ${file}`);
console.log(`  brands     : ${brands.join(', ')}`);
console.log(`  primitives : ${primitives.length}`);
console.log(`  repoints   : ${semantic.light.length} x 2 modes`);
